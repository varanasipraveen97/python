# Take two integers as input
m = int(input("Enter m: "))
n = int(input("Enter n: "))

# Compare using all comparison operators
print("m == n :", m == n)
print("m != n :", m != n)
print("m > n  :", m > n)
print("m < n  :", m < n)
print("m >= n :", m >= n)
print("m <= n :", m <= n)


